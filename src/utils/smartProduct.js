// يكشف منتجًا مشابهًا لدمجه كخيار (نفس الاسم الأساس بعد إزالة اللون/الحجم)
const VARIANT_WORDS = ["أخضر", "أصفر", "أحمر", "كبير", "صغير", "وسط", "علبة", "كيس", "زجاجة", "صغيرة", "كبيرة", "طازج", "مجمّد"];
const baseName = (name) => {
  let t = name;
  VARIANT_WORDS.forEach((w) => { t = t.replace(new RegExp(w, "g"), ""); });
  return norm(t).replace(/\s+/g, " ").trim();
};
export function findSimilar(products, name, excludeId) {
  const base = baseName(name);
  if (base.length < 3) return [];
  return products.filter((p) => p.id !== excludeId && baseName(p.name) === base);
}
