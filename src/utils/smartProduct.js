const norm = (s) => (s || "").toLowerCase().replace(/[أإآ]/g, "ا").replace(/ة/g, "ه").replace(/ى/g, "ي").trim();

// يقترح القسم والتفرّع من اسم المنتج
export function classify(name) {
  const t = norm(name);
  let best = null, score = 0;
  for (const r of RULES) {
    for (const k of r.kw) {
      const kn = norm(k);
      if (t.includes(kn)) { const sc = kn.length; if (sc > score) { score = sc; best = r; } }
    }
  }
  return best ? { cat: best.cat, sub: best.sub, matched: true } : { cat: "بقالة أساسية", sub: "", matched: false };
}

// يقترح سعرًا من متوسط أسعار المنتجات في نفس القسم/التفرّع
export function suggestPrice(products, cat, sub) {
  const pool = products.filter((p) => p.cat === cat && (!sub || p.sub === sub) && p.priceIQD);
  const use = pool.length >= 2 ? pool : products.filter((p) => p.cat === cat && p.priceIQD);
  if (!use.length) return null;
  const avg = use.reduce((a, p) => a + p.priceIQD, 0) / use.length;
  const price = Math.round(avg / 50) * 50; // تقريب لأقرب 50
  return { price, mrp: Math.round((price * 1.15) / 50) * 50, n: use.length };
}

// يقترح شارة حسب الخصم/الاسم
export function suggestBadge(name, price, mrp) {
  const off = mrp > price ? (mrp - price) / mrp : 0;
  if (off >= 0.2) return "عرض خاص";
  const t = norm(name);
  if (t.includes("جديد") || t.includes("new")) return "جديد";
  if (off > 0) return "عرض خاص";
  return "الأكثر مبيعاً";
}

